"""Generate code from the protocol folder's single sources.

    python tools/generate.py           write the generated files
    python tools/generate.py --check   write nothing; exit 1 naming each file that differs

It writes two files, because the browser app reads neither TOML nor traces:
  - app/src/generated/labpro-facts.ts, from protocol/labpro-facts.toml;
  - app/test/generated/fixtures.ts, from the fixtures in protocol/fixtures/,
    read with tools/traces.py, so that the trace format keeps one reader.
Python tools read the TOML and the traces directly, so they have no generated
copy. These are refused by name, never converted:
  - a value of a type the generator cannot write;
  - a number that is not finite;
  - an integer beyond the ones JavaScript holds exactly;
  - a file in protocol/fixtures/ that does not read as a fixture.
"""
import argparse
import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import labpro_facts  # noqa: E402
import traces  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = "app/src/generated/labpro-facts.ts"
FIXTURES = "protocol/fixtures/"
FIXTURES_OUTPUT = "app/test/generated/fixtures.ts"
FIELDS = ("value", "unit", "channels", "source", "page", "status")
MAX_SAFE = 2 ** 53 - 1  # JavaScript's Number.MAX_SAFE_INTEGER

PREAMBLE = """\
// Generated by tools/generate.py from protocol/labpro-facts.toml. Do not edit it by hand.
// After changing the facts, run `python tools/generate.py`. `python tools/check.py` fails
// while this file differs from what the generator makes, and loads it through Node to
// compare every value with the TOML's.
//
// Each fact names its source and the page it is read from. Status "manual" means read
// from the source and not yet seen on a bench; "bench" means confirmed on a LabPro.

export interface LabProFact {
  readonly value: number | string;
  readonly unit: string | null;
  readonly channels: string | null;
  readonly source: string;
  readonly page: number;
  readonly status: "manual" | "bench";
}

export const LABPRO_FACTS: Readonly<Record<string, LabProFact>> = Object.freeze({
"""

FIXTURES_PREAMBLE = """\
// Generated by tools/generate.py from the fixtures in protocol/fixtures/, read with
// tools/traces.py. Do not edit it by hand. After changing a fixture, run
// `python tools/generate.py`. `python tools/check.py` fails while this file differs from
// what the generator makes, and loads it through Node to compare it with the fixtures.
//
// A fixture is the lead's model of a LabPro, written from the manual; it is not evidence.
// Each transfer's bytes are written as a trace writes them: two-digit hex, one space apart.

export interface FixtureTransfer {
  readonly direction: "OUT" | "IN";
  readonly micros: number;
  readonly bytes: string;
}

export interface Fixture {
  readonly model: string;
  readonly transfers: readonly FixtureTransfer[];
}

export const FIXTURES: Readonly<Record<string, Fixture>> = Object.freeze({
"""


class Refused(ValueError):
    """Something the generator will not write, named."""


def literal(value, where):
    if value is None:
        return "null"
    if isinstance(value, bool):
        raise Refused(f"{where} is a boolean, which the app's facts do not carry")
    if isinstance(value, int):
        if abs(value) > MAX_SAFE:
            raise Refused(f"{where} is {value}, beyond the integers JavaScript holds exactly")
        return str(value)
    if isinstance(value, float):
        if not math.isfinite(value):
            raise Refused(f"{where} is not a finite number")
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    raise Refused(f"{where} is a {type(value).__name__}, which the generator cannot write")


def render(data):
    """The TypeScript text for the facts in data, the parsed facts file."""
    lines = [PREAMBLE.rstrip("\n")]
    for name, fact in labpro_facts.facts(data):
        fields = ", ".join(f"{field}: {literal(fact.get(field), f'{name}.{field}')}" for field in FIELDS)
        lines.append(f"  {json.dumps(name)}: Object.freeze({{ {fields} }}),")
    lines.append("});")
    return "\n".join(lines) + "\n"


def fixtures(root):
    """(file name, trace) for each .trace file in protocol/fixtures/ under root, by name.

    Refused for a file that does not read as a fixture.
    """
    found = []
    for path in sorted((Path(root) / FIXTURES).glob("*.trace")):
        try:
            trace = traces.parse(path.read_bytes().decode("utf-8"))
        except (UnicodeDecodeError, traces.TraceError) as exc:
            raise Refused(f"{FIXTURES}{path.name} does not read as a trace: {exc}") from None
        if trace.kind != "fixture":
            raise Refused(f"{FIXTURES}{path.name} is a {trace.kind}, not a fixture")
        found.append((path.name, trace))
    return found


def render_fixtures(found):
    """The TypeScript text for the fixtures in found, as fixtures() gives them."""
    lines = [FIXTURES_PREAMBLE.rstrip("\n")]
    for name, trace in found:
        lines.append(f"  {json.dumps(name)}: Object.freeze({{")
        lines.append(f"    model: {literal(trace.header['model'], f'{name} model')},")
        lines.append("    transfers: Object.freeze([")
        for number, (direction, micros, data) in enumerate(trace.transfers, start=1):
            where = f"{name} transfer {number}"
            lines.append(f"      Object.freeze({{ direction: {literal(direction, where)}, "
                         f"micros: {literal(micros, where)}, bytes: {literal(data.hex(' '), where)} }}),")
        lines.append("    ]),")
        lines.append("  }),")
    lines.append("});")
    return "\n".join(lines) + "\n"


def outputs(root):
    """{path: text} for every generated file, made from the sources under root."""
    return {OUTPUT: render(labpro_facts.load(root)), FIXTURES_OUTPUT: render_fixtures(fixtures(root))}


def main():
    parser = argparse.ArgumentParser(description="Generate code from the protocol folder's single sources.")
    parser.add_argument("--check", action="store_true", help="write nothing; fail if a generated file differs")
    args = parser.parse_args()
    try:
        made = outputs(ROOT)
    except Refused as exc:
        sys.exit(f"refused: {exc}")
    differs = False
    for name, text in made.items():
        path = ROOT / name
        current = path.read_bytes() if path.is_file() else None
        if current == text.encode("utf-8"):
            print(f"{name} is what this generator makes" if args.check else f"{name} already up to date")
            continue
        if args.check:
            print(f"{name} differs from what this generator makes; run python tools/generate.py")
            differs = True
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))
        print(f"wrote {name}")
    if differs:
        sys.exit(1)


if __name__ == "__main__":
    main()
